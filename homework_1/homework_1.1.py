#1. Привести к целому типу -1.6, 2.99
number_1 = -1.6
number_2 = 2.99

int_number_1 = int(number_1)
int_number_2 = int(number_2)

result1 = "Значение до приведения: {}, значение после приведения к целому: {}".format(number_1, int_number_1)
print(result1)

result2 = "Значение до приведения: {}, значение после приведения к целому: {}".format(number_2, int_number_2)
print(result2)

# Дан файл целых чисел, содержащий не менее четырех элементов.
# Вывести первый, второй, предпоследний и последний элементы данного файла.
# Если чисел меньше 3 выводить ошибку.

with open("for_hw4.1.txt","r") as f:
    l=f.readlines()
    quantity_of_lines=len(l)
    if quantity_of_lines < 3:
        print("Нельзя выполнить функцию! В файле менее 3х значений")
    else:
        print(l[0].strip(),
          l[1].strip(),
          l[-2].strip(),
          l[-1].strip())
